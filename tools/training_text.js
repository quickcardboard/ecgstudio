// Writes docs/TRAINING_TEXT.md: every piece of teaching text Training shows, for the author to review.
//   node tools/training_text.js
// 1. Diagnosis names (the answer chips) from src/training_vocab.txt
// 2. Explanation lines (a result chip tapped; the line under the score) from src/training_gen.js and src/training.js
// 3. Learn text (the simulator's Learn tab, opened by "Show me why") from src/app.js
const fs = require('fs'), path = require('path');
const R = (f) => fs.readFileSync(path.join(__dirname, '..', f), 'utf8');
const TrainGen = require('../src/training_gen.js');
const out = [];
const w = (s = '') => out.push(s);

w('# Training text for review');
w();
w('Generated by `node tools/training_text.js` from the source files; edit the sources (named in each section), not this file.');
w('In the dynamic lines, `‹leads›` is filled with the leads the ECG shows, `‹wall›` with the wall (e.g. inferior), `‹h›` with hours.');
w();

// 1. vocabulary
w('## 1. Diagnosis names (the answer chips)');
w();
w('Source: `src/training_vocab.txt`. Name shown on the chip, then what the user can type to find it. **Region** = the ECG then asks for the lead groups.');
let sec = null;
for (const raw of R('src/training_vocab.txt').split('\n')) {
  const line = raw.trim();
  if (line.startsWith('## ')) { sec = line.slice(3); w(); w(`### ${sec}`); w(); w('| Name | Typed as | |'); w('|---|---|---|'); continue; }
  if (!line || line.startsWith('#') || !sec) continue;
  const [, name, syn = '', flags = ''] = line.split('|').map((x) => x.trim());
  w(`| ${name} | ${syn.replace(/\|/g, '/')} | ${/region/.test(flags) ? 'region' : ''} |`);
}
w();

// 2. explanation lines
const gen = R('src/training_gen.js');
const block = (src, start) => {   // the object literal that starts at `start`
  const i = src.indexOf(start); if (i < 0) throw new Error(`not found: ${start}`);
  let d = 0, j = src.indexOf('{', i);
  for (let k = j; k < src.length; k++) { if (src[k] === '{') d++; else if (src[k] === '}' && --d === 0) return src.slice(j, k + 1); }
  throw new Error('unbalanced');
};
const RHYTHM_LINE = Function(`return ${block(gen, 'const RHYTHM_LINE = {')}`)();
const VOC = {}; for (const raw of R('src/training_vocab.txt').split('\n')) { const p = raw.split('|').map((x) => x.trim()); if (p.length >= 2 && !raw.trim().startsWith('#')) VOC[p[0]] = p[1]; }
const RNAME = { flutterVar: 'Atrial flutter (variable block)', flutter21: 'Atrial flutter (2:1)', avb2to1: '2:1 AV block (answered as Mobitz II)' };
w('## 2. Explanation lines (tap a chip on the result, or the line under the score)');
w();
w('Sources: `RHYTHM_LINE` and `ABN` (`line:`) in `src/training_gen.js`; the dynamic lines are written in `build()` there; the');
w('scoring messages in `src/training.js` (`oneLine`, `rowLine`, `score`).');
w();
w('### Rhythms');
w();
w('| Rhythm | Line |'); w('|---|---|');
for (const [k, v] of Object.entries(RHYTHM_LINE)) w(`| ${RNAME[k] || VOC[k] || k} | ${v} |`);
w();
w('### Findings (fixed lines)');
w();
w('| Finding | Line |'); w('|---|---|');
const seen = new Set();
for (const [k, a] of Object.entries(TrainGen.ABN)) {
  if (!a.line) continue;
  const id = a.id || k, name = VOC[id] || id, label = k === 'hyperK2' ? 'Hyperkalemia (severe)' : k === 'wellensA' ? 'Wellens (type A)' : k === 'wellensB' ? 'Wellens (type B)' : name;
  if (seen.has(label)) continue; seen.add(label);
  w(`| ${label} | ${a.line} |`);
}
w('| Sinus pause (with escape) | A sudden pause with no P wave, not a multiple of the P–P interval, ended by a narrow junctional escape beat (no P before it), then sinus beats resume: sinus pause with junctional escape. |');
w('| Acute pericarditis (no P waves, e.g. AF) | Diffuse concave ST elevation with ST depression in aVR (no PR segment to read): pericarditis. |');
w();
w('### Findings (lines written for each ECG)');
w();
w('| Finding | Line |'); w('|---|---|');
const DYN = [
  ['ST elevation (acute STEMI)', 'ST elevation in ‹leads›: acute ‹wall› STEMI.'],
  ['ST elevation (evolving, 4 h / 12 h)', 'ST elevation in ‹leads›, past its peak, with Q waves forming[ and T waves starting to invert]: an evolving ‹wall› STEMI, about ‹h› hours old.'],
  ['ST elevation in LBBB (Sgarbossa)', '‹the criteria met›: Sgarbossa criteria (modified) positive, an acute ‹wall› STEMI despite the LBBB.'],
  ['Q waves (old infarct)', 'Q waves in ‹leads›: old ‹wall› infarct.'],
  ['Q waves + T wave inversion (recent infarct, 2 days)', 'Q waves in ‹leads›, T inversion in ‹leads›: recent ‹wall› infarct (days old).'],
  ['…when its ST still meets the STEMI criteria (new)', '…+ The ST is still raised, so ST elevation counts in place of the T inversion: treat it as a STEMI until shown otherwise.'],
  ['Hyperacute T waves', 'Tall, broad T waves in ‹leads›, no ST elevation yet: hyperacute ‹wall› ischemia. Repeat the ECG.'],
  ['ST depression (one artery narrowed)', 'ST depression in ‹leads›[, ST up in aVR]: subendocardial ischemia (NSTEMI pattern). It does not localise the artery.'],
  ['ST depression (several arteries)', 'Widespread ST depression in ‹leads›: diffuse subendocardial ischemia, not one territory. With ST elevation in aVR (‹x› mm): the left main or multivessel pattern (here ‹arteries› narrowed). Urgent: it does not localise to one artery.'],
  ['Non-specific ST-T abnormality', 'Flat T waves in ‹leads›, no territory, no ST depression or Q waves: non-specific ST-T changes.'],
  ['ST depression, also true', 'ST depression in ‹leads›[, the strain pattern of LVH]: also true on this ECG.'],
  ['Q waves, also true', 'Q waves in ‹leads›: also true on this ECG. (With a right axis and only II, III, aVF: Q waves in ‹leads›: a qR pattern from the right axis, not an infarct; also true on this ECG.)'],
  ['T wave inversion, also true', 'T wave inversion in ‹leads›: also true on this ECG.'],
];
for (const [a, b] of DYN) w(`| ${a} | ${b} |`);
w();
w('### Scoring messages');
w();
w('| When | Text |'); w('|---|---|');
const MSG = [
  ['All right (line under the score)', 'Correct. ‹the main finding’s line›'],
  ['Wrong rhythm', 'Not ‹your rhythm›. ‹the rhythm’s line›'],
  ['A finding named that is not there', '‹finding›: not present. ‹the main finding’s line›  (on its chip: ‹finding›: not present on this ECG.)'],
  ['A true secondary finding named', 'Chip tag: also true. Line: ‹finding›: also true on this ECG (a secondary finding), credited but not required.'],
  ['Rhythm partly right', 'Chip tag: more exactly: ‹rhythm›'],
  ['Right finding, wrong lead groups', 'Chip tag: leads: ‹lead groups›'],
  ['Beats named, not their pattern', 'Chip tag: more exactly: ‹pattern› (e.g. PVCs for bigeminy)'],
  ['Advanced finding, below its rating', 'Chip tag: advanced: asked from ‹rating›   (named anyway: tag advanced)'],
  ['First-degree AV block named in sinus tachycardia (new)', 'Chip tag: cannot be judged here. Line: First-degree AV block: at this rate the P wave sits on the end of the T wave, so the PR is hard to judge by eye. The measured PR is ‹PR› ms. Neither credited nor counted against you.'],
  ['LAFB or bifascicular block named with RBBB alone (new)', 'Chip tag: cannot be judged here. Line: ‹finding›: in this simulator a right bundle branch block on its own already turns the axis left (about −50°), so an added left anterior fascicular block cannot be told apart. Neither credited nor counted against you.'],
];
for (const [a, b] of MSG) w(`| ${a} | ${b} |`);
w();

// 3. learn text
const app = R('src/app.js');
const TEACH = Function(`return ${block(app, 'const TEACH = {')}`)(), ISCH = Function(`return ${block(app, 'const ISCH_TEACH = {')}`)();
w('## 3. Learn text (the simulator’s Learn tab; Training opens it with “Show me why”)');
w();
w('Source: `TEACH` and `ISCH_TEACH` in `src/app.js`. Each entry shows its key features; the pitfalls of every entry on screen are listed together under “Pitfalls”.');
for (const [k, it] of [...Object.entries(TEACH), ...Object.entries(ISCH)]) {
  w(); w(`### ${it.t}`); w();
  for (const f of it.f) w(`- ${f}`);
  if (it.p && it.p.length) { w(); w('Pitfalls:'); w(); for (const p of it.p) w(`- ${p}`); }
}
w();
fs.writeFileSync(path.join(__dirname, '..', 'docs/TRAINING_TEXT.md'), out.join('\n'));
console.log(`docs/TRAINING_TEXT.md: ${out.length} lines`);
